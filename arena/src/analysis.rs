/// Version of the persisted Arena analysis schema.
pub const ANALYSIS_SCHEMA_VERSION: u32 = 1;
/// Flat per-game metrics output generated by [`DatasetAnalyzer`].
pub const GAME_METRICS_FILE_NAME: &str = "game_metrics.csv";
/// Aggregate metrics output generated by [`DatasetAnalyzer`].
pub const SUMMARY_FILE_NAME: &str = "summary.json";

static NEXT_TEMPORARY_OUTPUT: AtomicU64 = AtomicU64::new(0);

/// Analyzes one complete persisted dataset without modifying its raw records.
#[derive(Debug, Copy, Clone, Default)]
pub struct DatasetAnalyzer;

impl DatasetAnalyzer {
    /// Replay every game and create `game_metrics.csv` plus `summary.json`.
    ///
    /// Existing derived outputs are never overwritten. Temporary files are
    /// removed when analysis returns an error.
    pub fn analyze(root: impl AsRef<Path>) -> Result<AnalysisReport, AnalysisError> {
        let mut reader = JsonlDatasetReader::open(root)?;
        let manifest = reader.manifest().clone();
        let dataset_root = reader.root().to_path_buf();
        let game_metrics_path = dataset_root.join(GAME_METRICS_FILE_NAME);
        let summary_path = dataset_root.join(SUMMARY_FILE_NAME);
        ensure_output_absent(&game_metrics_path)?;
        ensure_output_absent(&summary_path)?;

        let mut game_metrics_temp = TemporaryOutput::new(&dataset_root, GAME_METRICS_FILE_NAME);
        let game_metrics_file =
            OpenOptions::new().write(true).create_new(true).open(game_metrics_temp.path())?;
        let mut game_metrics_writer = BufWriter::new(game_metrics_file);
        write_csv_header(&mut game_metrics_writer)?;

        let mut accumulator = SummaryAccumulator::new(&manifest);
        for record in &mut reader {
            let record = record?;
            validate_record_dimensions(&manifest, &record)?;
            let metrics = GameMetrics::from_record(&record)?;
            write_game_metrics_row(&mut game_metrics_writer, &metrics)?;
            accumulator.record(&record, &metrics)?;
        }
        game_metrics_writer.flush()?;
        drop(game_metrics_writer);

        let games_analyzed = reader.read_games();
        let summary = accumulator.finish(&manifest);
        let mut summary_temp = TemporaryOutput::new(&dataset_root, SUMMARY_FILE_NAME);
        let summary_file =
            OpenOptions::new().write(true).create_new(true).open(summary_temp.path())?;
        let mut summary_writer = BufWriter::new(summary_file);
        serde_json::to_writer_pretty(&mut summary_writer, &summary)?;
        summary_writer.write_all(b"\n")?;
        summary_writer.flush()?;
        drop(summary_writer);

        game_metrics_temp.commit(&game_metrics_path)?;
        if let Err(error) = summary_temp.commit(&summary_path) {
            let _ = fs::remove_file(&game_metrics_path);
            return Err(AnalysisError::Io(error));
        }

        Ok(AnalysisReport { dataset_root, game_metrics_path, summary_path, games_analyzed })
    }
}

