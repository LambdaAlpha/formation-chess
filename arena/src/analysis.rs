#[derive(Default)]
struct ActionAccumulator {
    all_per_game: PhaseActionDistributionAccumulator,
    red_per_game: PhaseActionDistributionAccumulator,
    black_per_game: PhaseActionDistributionAccumulator,
    action_types: ActionTypeAccumulator,
    legal_movement_actions: IntegerDistributionAccumulator,
}

impl ActionAccumulator {
    fn record(&mut self, record: &GameRecord, metrics: &GameMetrics) {
        let red = &metrics.actions_by_side.red;
        let black = &metrics.actions_by_side.black;
        self.all_per_game.record(
            metrics.action_types.total_actions,
            red.placement_actions + black.placement_actions,
            red.movement_actions + black.movement_actions,
        );
        self.red_per_game.record(red.total_actions, red.placement_actions, red.movement_actions);
        self.black_per_game.record(
            black.total_actions,
            black.placement_actions,
            black.movement_actions,
        );
        self.action_types.record(&metrics.action_types);
        for legal_count in record.actions.iter().filter_map(|action| action.legal_action_count) {
            self.legal_movement_actions.record(legal_count);
        }
    }

    fn finish(self) -> ActionSummary {
        let action_types = self.action_types.finish();
        ActionSummary {
            total_actions: action_types.total_actions,
            all_per_game: self.all_per_game.finish(),
            red_per_game: self.red_per_game.finish(),
            black_per_game: self.black_per_game.finish(),
            action_types,
            legal_movement_actions: self.legal_movement_actions.finish(),
        }
    }
}

