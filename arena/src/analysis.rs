fn push_termination_fields(fields: &mut Vec<CsvField>, termination: crate::TerminationKind) {
    match termination {
        crate::TerminationKind::Completed => {
            fields.push(text("completed"));
            fields.extend([CsvField::Empty, CsvField::Empty, CsvField::Empty]);
        },
        crate::TerminationKind::ActionLimit { limit } => {
            fields.push(text("action_limit"));
            fields.push(raw(limit));
            fields.extend([CsvField::Empty, CsvField::Empty]);
        },
        crate::TerminationKind::AgentFailure { player, phase } => {
            fields.push(text("agent_failure"));
            fields.push(CsvField::Empty);
            fields.push(text(player_name(player)));
            fields.push(text(phase_name(phase)));
        },
    }
}

fn push_last_action_fields(fields: &mut Vec<CsvField>, action: Option<&crate::LastActionMetrics>) {
    let Some(action) = action else {
        fields.extend([
            CsvField::Empty,
            CsvField::Empty,
            CsvField::Empty,
            CsvField::Empty,
            CsvField::Empty,
        ]);
        return;
    };
    fields.push(raw(action.action_index));
    fields.push(text(player_name(action.player)));
    fields.push(text(phase_name(action.phase)));
    fields.push(text(action_kind_name(action.action_kind)));
    fields.push(text(&action.notation));
}

fn push_count_ratio_fields(fields: &mut Vec<CsvField>, ratio: CountRatio) {
    fields.push(raw(ratio.count));
    fields.push(optional_raw(ratio.ratio));
}

fn push_distribution_fields(fields: &mut Vec<CsvField>, distribution: DistributionMetrics) {
    fields.push(raw(distribution.count));
    fields.push(optional_raw(distribution.min));
    fields.push(optional_raw(distribution.max));
    fields.push(optional_raw(distribution.mean));
    fields.push(optional_raw(distribution.median));
    fields.push(optional_raw(distribution.p25));
    fields.push(optional_raw(distribution.p75));
    fields.push(optional_raw(distribution.p90));
    fields.push(optional_raw(distribution.p95));
}

fn write_csv_row(writer: &mut impl Write, fields: &[CsvField]) -> io::Result<()> {
    if fields.len() != CSV_COLUMNS.len() {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            format!("CSV row has {} fields, expected {}", fields.len(), CSV_COLUMNS.len()),
        ));
    }
    for (index, field) in fields.iter().enumerate() {
        if index != 0 {
            writer.write_all(b",")?;
        }
        match field {
            CsvField::Raw(value) => writer.write_all(value.as_bytes())?,
            CsvField::Text(value) => {
                writer.write_all(b"\"")?;
                writer.write_all(value.replace('"', "\"\"").as_bytes())?;
                writer.write_all(b"\"")?;
            },
            CsvField::Empty => {},
        }
    }
    writer.write_all(b"\n")
}

fn raw(value: impl Display) -> CsvField {
    CsvField::Raw(value.to_string())
}

fn optional_raw(value: Option<impl Display>) -> CsvField {
    value.map_or(CsvField::Empty, raw)
}

fn text(value: &str) -> CsvField {
    CsvField::Text(value.to_owned())
}

fn count_ratio(count: u64, total: u64) -> CountRatio {
    let ratio = if total == 0 { None } else { Some(count as f64 / total as f64) };
    CountRatio { count, ratio }
}

fn participant_outcomes(result: GameResultRecord) -> (ParticipantOutcome, ParticipantOutcome) {
    match result {
        GameResultRecord::RedWin => (ParticipantOutcome::Win, ParticipantOutcome::Loss),
        GameResultRecord::BlackWin => (ParticipantOutcome::Loss, ParticipantOutcome::Win),
        GameResultRecord::Draw => (ParticipantOutcome::Draw, ParticipantOutcome::Draw),
        GameResultRecord::Unfinished => {
            (ParticipantOutcome::Unfinished, ParticipantOutcome::Unfinished)
        },
    }
}

fn float_percentile(sorted: &[f64], probability: f64) -> f64 {
    debug_assert!(!sorted.is_empty(), "percentiles require at least one observation");
    let index = (sorted.len() - 1) as f64 * probability;
    let lower = index.floor() as usize;
    let upper = index.ceil() as usize;
    sorted[lower] + (sorted[upper] - sorted[lower]) * (index - lower as f64)
}

fn ensure_output_absent(path: &Path) -> Result<(), AnalysisError> {
    if path.exists() { Err(AnalysisError::OutputExists(path.to_path_buf())) } else { Ok(()) }
}

fn validate_record_dimensions(
    manifest: &ArenaManifest, record: &GameRecord,
) -> Result<(), AnalysisError> {
    let participant_a = manifest.participant_a.id.as_str();
    let participant_b = manifest.participant_b.id.as_str();
    let valid = match manifest.schedule {
        ScheduleRecord::Fixed { .. } => {
            record.pair_id.is_none()
                && record.game_in_pair.is_none()
                && record.red.participant_id == participant_a
                && record.black.participant_id == participant_b
        },
        ScheduleRecord::Paired { .. } => {
            let pair_id = record.game_id / 2;
            let game_in_pair = (record.game_id % 2) as u8;
            let seats_match = if game_in_pair == 0 {
                record.red.participant_id == participant_a
                    && record.black.participant_id == participant_b
            } else {
                record.red.participant_id == participant_b
                    && record.black.participant_id == participant_a
            };
            record.pair_id == Some(pair_id)
                && record.game_in_pair == Some(game_in_pair)
                && seats_match
        },
    };
    if valid {
        Ok(())
    } else {
        Err(AnalysisError::InvalidRecord {
            game_id: record.game_id,
            message: "pair or participant seats differ from the manifest schedule".to_owned(),
        })
    }
}

const fn game_result_name(result: GameResultRecord) -> &'static str {
    match result {
        GameResultRecord::Unfinished => "unfinished",
        GameResultRecord::RedWin => "red_win",
        GameResultRecord::BlackWin => "black_win",
        GameResultRecord::Draw => "draw",
    }
}

const fn player_name(player: PlayerRecord) -> &'static str {
    match player {
        PlayerRecord::Red => "red",
        PlayerRecord::Black => "black",
    }
}

const fn phase_name(phase: PhaseRecord) -> &'static str {
    match phase {
        PhaseRecord::Placement => "placement",
        PhaseRecord::Movement => "movement",
    }
}

const fn action_kind_name(action: ActionKind) -> &'static str {
    match action {
        ActionKind::Place => "place",
        ActionKind::Move => "move",
        ActionKind::Capture => "capture",
        ActionKind::Push => "push",
        ActionKind::Draw => "draw",
        ActionKind::Divide => "divide",
        ActionKind::Pass => "pass",
        ActionKind::Resign => "resign",
    }
}
