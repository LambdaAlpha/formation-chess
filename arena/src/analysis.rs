#[derive(Default)]
struct ResultAccumulator {
    red_wins: u64,
    black_wins: u64,
    draws: u64,
    unfinished: u64,
}

impl ResultAccumulator {
    fn record(&mut self, result: GameResultRecord) {
        match result {
            GameResultRecord::RedWin => self.red_wins += 1,
            GameResultRecord::BlackWin => self.black_wins += 1,
            GameResultRecord::Draw => self.draws += 1,
            GameResultRecord::Unfinished => self.unfinished += 1,
        }
    }

    fn finish(self, games: u64) -> ResultSummary {
        ResultSummary {
            red_wins: count_ratio(self.red_wins, games),
            black_wins: count_ratio(self.black_wins, games),
            draws: count_ratio(self.draws, games),
            unfinished: count_ratio(self.unfinished, games),
        }
    }
}

