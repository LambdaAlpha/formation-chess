#[derive(Default)]
struct StateAccumulator {
    totals: StateVisitTotals,
    total_visits_per_game: IntegerDistributionAccumulator,
    unique_states_per_game: IntegerDistributionAccumulator,
    repeated_visits_per_game: IntegerDistributionAccumulator,
    unique_state_ratio_per_game: FloatDistributionAccumulator,
}

impl StateAccumulator {
    fn record(&mut self, metrics: &crate::StateVisitMetrics) {
        self.totals.total_visits += metrics.total_visits;
        self.totals.unique_states += metrics.unique_states;
        self.totals.repeated_visits += metrics.repeated_visits;
        self.total_visits_per_game.record(metrics.total_visits);
        self.unique_states_per_game.record(metrics.unique_states);
        self.repeated_visits_per_game.record(metrics.repeated_visits);
        self.unique_state_ratio_per_game.record(metrics.unique_state_ratio);
    }

    fn finish(mut self) -> StateSummary {
        self.totals.unique_state_ratio = if self.totals.total_visits == 0 {
            None
        } else {
            Some(self.totals.unique_states as f64 / self.totals.total_visits as f64)
        };
        StateSummary {
            totals: self.totals,
            total_visits_per_game: self.total_visits_per_game.finish(),
            unique_states_per_game: self.unique_states_per_game.finish(),
            repeated_visits_per_game: self.repeated_visits_per_game.finish(),
            unique_state_ratio_per_game: self.unique_state_ratio_per_game.finish(),
        }
    }
}

