/// Failure to analyze or persist derived metrics.
#[derive(Debug)]
pub enum AnalysisError {
    OutputExists(PathBuf),
    InvalidRecord { game_id: u64, message: String },
    Dataset(DatasetError),
    Metrics(MetricsError),
    Json(serde_json::Error),
    Io(io::Error),
}

impl Display for AnalysisError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::OutputExists(path) => {
                write!(formatter, "analysis output already exists: {}", path.display())
            },
            Self::InvalidRecord { game_id, message } => {
                write!(formatter, "game {game_id} has invalid analysis dimensions: {message}")
            },
            Self::Dataset(error) => Display::fmt(error, formatter),
            Self::Metrics(error) => Display::fmt(error, formatter),
            Self::Json(error) => write!(formatter, "analysis JSON processing failed: {error}"),
            Self::Io(error) => write!(formatter, "analysis I/O failed: {error}"),
        }
    }
}

impl Error for AnalysisError {
    fn source(&self) -> Option<&(dyn Error + 'static)> {
        match self {
            Self::Dataset(error) => Some(error),
            Self::Metrics(error) => Some(error),
            Self::Json(error) => Some(error),
            Self::Io(error) => Some(error),
            Self::OutputExists(_) | Self::InvalidRecord { .. } => None,
        }
    }
}

impl From<DatasetError> for AnalysisError {
    fn from(error: DatasetError) -> Self {
        Self::Dataset(error)
    }
}

impl From<MetricsError> for AnalysisError {
    fn from(error: MetricsError) -> Self {
        Self::Metrics(error)
    }
}

impl From<serde_json::Error> for AnalysisError {
    fn from(error: serde_json::Error) -> Self {
        Self::Json(error)
    }
}

impl From<io::Error> for AnalysisError {
    fn from(error: io::Error) -> Self {
        Self::Io(error)
    }
}

